export type PortfolioNetwork = (typeof PORTFOLIO_NETWORKS)[number];

const NETWORKS: ReadonlySet<string> = new Set(PORTFOLIO_NETWORKS);

/** Wallet currency ids the service names differently. */
const CURRENCY_ID_ALIASES: Readonly<Record<string, PortfolioNetwork>> = {
  ripple: "xrp",
};

/** The service's name for a wallet currency id, or undefined when the service does not know it. */
export function portfolioNetworkOf(currencyId: string): PortfolioNetwork | undefined {
  const candidate = CURRENCY_ID_ALIASES[currencyId] ?? currencyId;
  return NETWORKS.has(candidate) ? (candidate as PortfolioNetwork) : undefined;
}
