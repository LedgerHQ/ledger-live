import { BigNumber } from "bignumber.js";
import { NotEnoughBalance } from "@ledgerhq/ledger-wallet-framework/errors";
import type { TransactionInfo } from "@ledgerhq/wallet-btc/index";
import type { Operation, SignedOperation } from "@ledgerhq/types-live";
import type { Transaction, ZcashAccount } from "../types/bridge";
import { TM_ADDRESS } from "../__tests__/fixtures/testnetAddresses";
import { contextWithZip2009, testContext } from "../test/coinConfig";
import { buildLegacyTransaction, resolveWalletAccount } from "./buildTransaction";
import { buildLegacyPrepareTransaction } from "./prepareTransaction";
import { buildLegacyGetTransactionStatus } from "./getTransactionStatus";
import { buildLegacyEstimateMaxSpendable } from "./estimateMaxSpendable";
import { buildLegacyBroadcast } from "./broadcast";

const estimateAccountMaxSpendable = jest.fn();
const broadcastTx = jest.fn();

jest.mock("./buildTransaction");
const zcashSafeFeePerByte = jest.fn((..._args: unknown[]) => new BigNumber(40));

jest.mock("./fees", () => ({
  zcashSafeFeePerByte: (...args: unknown[]) => zcashSafeFeePerByte(...args),
}));
jest.mock("@ledgerhq/wallet-btc/index", () => ({
  __esModule: true,
  default: {
    estimateAccountMaxSpendable: (...args: unknown[]) => estimateAccountMaxSpendable(...args),
    broadcastTx: (...args: unknown[]) => broadcastTx(...args),
  },
}));

const mockResolveWalletAccount = resolveWalletAccount as jest.MockedFunction<
  typeof resolveWalletAccount
>;
const mockBuild = buildLegacyTransaction as jest.MockedFunction<typeof buildLegacyTransaction>;

// A real mainnet P2PKH address (the one coin-zcash's address tests use).
const T1 = "t1b1Rbw2shhJkP6MCnCyxCPuyFedHrwKty8";
// An Orchard-only Unified Address generated by the Zcash device app.
const UA_ORCHARD =
  "u1u2h4ce7e2cn3z4nzur95muq2dl4da9x8h8kdp2l80gm9nl9raj8zzpx79ycjnfvar4v5exea5pqr5y9qsnlp0cdunwf9yjjx5c4q7ar9";

const account = {
  type: "Account",
  id: "js:2:zcash:xpub:",
  currency: { id: "zcash", name: "Zcash" },
} as unknown as ZcashAccount;

// Heights either side of the ZIP 2009 switch (3_590_000, applied 100 blocks late).
const accountAt = (id: string, blockHeight: number): ZcashAccount =>
  ({ ...account, currency: { id, name: "Zcash" }, blockHeight }) as unknown as ZcashAccount;
// A test network refuses a mainnet address, so each account gets one of its own.
const recipientOf = (acc: ZcashAccount): string =>
  acc.currency.id === "zcash_testnet" ? TM_ADDRESS : T1;
const PRICED_AT = [
  ["mainnet below the switch", accountAt("zcash", 3_590_098), 5_000],
  ["mainnet past the switch", accountAt("zcash", 3_590_099), 1_000],
  ["testnet at height 0", accountAt("zcash_testnet", 0), 1_000],
] as [string, ZcashAccount, number][];

const tx = (fields: Partial<Transaction>): Transaction =>
  ({
    family: "zcash",
    amount: new BigNumber(100_000),
    recipient: T1,
    transferType: "transparent",
    useAllAmount: false,
    ...fields,
  }) as Transaction;

const built = (fee: number, recipientValue: number, change: number): TransactionInfo =>
  ({
    inputs: [{ value: new BigNumber(recipientValue + change + fee) }],
    outputs: [
      { value: new BigNumber(recipientValue), isChange: false },
      ...(change > 0 ? [{ value: new BigNumber(change), isChange: true }] : []),
    ],
    associatedDerivations: [],
    fee,
    changeAddress: { account: 1, index: 0, address: "" },
  }) as unknown as TransactionInfo;

const fetchUtxoTx = jest.fn();

beforeEach(() => {
  jest.clearAllMocks();
  mockResolveWalletAccount.mockResolvedValue({
    xpub: { crypto: {}, derivationMode: "", explorer: { fetchUtxoTx } },
  } as unknown as Awaited<ReturnType<typeof resolveWalletAccount>>);
  mockBuild.mockResolvedValue({
    txInfo: built(10_000, 100_000, 50_000),
    feePerByte: new BigNumber(40),
  });
});

describe("buildLegacyPrepareTransaction", () => {
  const prepare = buildLegacyPrepareTransaction(testContext);

  it("sets the fee and change of the build", async () => {
    const prepared = await prepare(account, tx({}));

    expect(prepared.zcashFee?.toNumber()).toBe(10_000);
    expect(prepared.changeAmount?.toNumber()).toBe(50_000);
    expect(prepared.selectedNotes).toEqual([]);
  });

  it("takes the amount from the single recipient output when sending everything", async () => {
    mockBuild.mockResolvedValue({
      txInfo: built(10_000, 140_000, 0),
      feePerByte: new BigNumber(40),
    });

    const prepared = await prepare(account, tx({ useAllAmount: true }));

    expect(prepared.amount.toNumber()).toBe(140_000);
  });

  it("leaves a shielded recipient unpriced, without building", async () => {
    const prepared = await prepare(
      account,
      tx({ recipient: UA_ORCHARD, zcashFee: new BigNumber(1) }),
    );

    expect(mockBuild).not.toHaveBeenCalled();
    expect(prepared.zcashFee).toBeUndefined();
  });

  it("leaves the transaction unpriced when the balance cannot cover it", async () => {
    mockBuild.mockRejectedValue(new NotEnoughBalance());

    expect((await prepare(account, tx({}))).zcashFee).toBeUndefined();
  });

  it.each([
    ["the balance cannot cover it", { recipient: T1 }],
    ["the recipient is refused", { recipient: UA_ORCHARD }],
  ])("drops a resolved send-all amount when %s", async (_label, fields) => {
    mockBuild.mockRejectedValue(new NotEnoughBalance());

    const prepared = await prepare(
      account,
      tx({ ...fields, useAllAmount: true, amount: new BigNumber(140_000) }),
    );

    expect(prepared.amount.toNumber()).toBe(0);
    expect(prepared.zcashFee).toBeUndefined();
  });

  it("keeps the amount typed in when the balance cannot cover it", async () => {
    mockBuild.mockRejectedValue(new NotEnoughBalance());

    expect((await prepare(account, tx({}))).amount.toNumber()).toBe(100_000);
  });
});

describe("legacy pricing follows the account's marginal fee", () => {
  it.each(PRICED_AT)(
    "prepares %s at the account's marginal fee",
    async (_label, acc, marginalFee) => {
      await buildLegacyPrepareTransaction(testContext)(acc, tx({ recipient: recipientOf(acc) }));

      expect(mockBuild).toHaveBeenCalledWith(
        expect.anything(),
        expect.anything(),
        expect.anything(),
        marginalFee,
      );
    },
  );

  it.each(PRICED_AT)(
    "prices the status of %s at the account's marginal fee",
    async (_label, acc, marginalFee) => {
      await buildLegacyGetTransactionStatus(testContext)(acc, tx({ recipient: recipientOf(acc) }));

      expect(mockBuild).toHaveBeenCalledWith(
        expect.anything(),
        expect.anything(),
        expect.anything(),
        marginalFee,
      );
    },
  );

  it.each(PRICED_AT)(
    "derives the safe rate of %s from the account's marginal fee",
    async (_label, acc, marginalFee) => {
      estimateAccountMaxSpendable.mockResolvedValue(new BigNumber(1));

      await buildLegacyEstimateMaxSpendable(testContext)({ account: acc });

      expect(zcashSafeFeePerByte).toHaveBeenCalledWith(
        expect.anything(),
        expect.anything(),
        marginalFee,
      );
    },
  );
});

describe("legacy pricing follows the zip2009 coin config", () => {
  const delayed = contextWithZip2009({ mainnetHeight: 3_700_000 });
  const disabled = contextWithZip2009({ mainnetHeight: null });
  const past = accountAt("zcash", 3_600_000);

  it("prepares at the fee of the setting", async () => {
    await buildLegacyPrepareTransaction(delayed)(past, tx({}));
    expect(mockBuild).toHaveBeenLastCalledWith(
      expect.anything(),
      expect.anything(),
      expect.anything(),
      5_000,
    );

    await buildLegacyPrepareTransaction(testContext)(past, tx({}));
    expect(mockBuild).toHaveBeenLastCalledWith(
      expect.anything(),
      expect.anything(),
      expect.anything(),
      1_000,
    );
  });

  it("prices the status at the fee of the setting", async () => {
    await buildLegacyGetTransactionStatus(disabled)(past, tx({}));

    expect(mockBuild).toHaveBeenLastCalledWith(
      expect.anything(),
      expect.anything(),
      expect.anything(),
      5_000,
    );
  });

  it("derives the safe rate from the fee of the setting", async () => {
    estimateAccountMaxSpendable.mockResolvedValue(new BigNumber(1));

    await buildLegacyEstimateMaxSpendable(delayed)({ account: past });

    expect(zcashSafeFeePerByte).toHaveBeenLastCalledWith(
      expect.anything(),
      expect.anything(),
      5_000,
    );
  });
});

describe("buildLegacyGetTransactionStatus", () => {
  const status = buildLegacyGetTransactionStatus(testContext);

  it("reports the fee and what the send spends", async () => {
    const result = await status(account, tx({}));

    expect(result.errors).toEqual({});
    expect(result.estimatedFees.toNumber()).toBe(10_000);
    expect(result.totalSpent.toNumber()).toBe(110_000);
  });

  it("refuses a shielded recipient", async () => {
    const result = await status(account, tx({ recipient: UA_ORCHARD }));

    expect(result.errors.recipient?.name).toBe("ZcashShieldedKeyMissing");
    expect(mockBuild).not.toHaveBeenCalled();
  });

  it("reports an amount the balance cannot cover", async () => {
    mockBuild.mockRejectedValue(new NotEnoughBalance());

    expect((await status(account, tx({}))).errors.amount).toBeInstanceOf(NotEnoughBalance);
  });

  it("refuses an amount below the transparent dust threshold", async () => {
    const result = await status(account, tx({ amount: new BigNumber(1) }));

    expect(result.errors.amount?.name).toBe("ZcashAmountBelowDustThreshold");
  });
});

describe("buildLegacyEstimateMaxSpendable", () => {
  const estimate = buildLegacyEstimateMaxSpendable(testContext);

  it("asks wallet-btc for the max at the safe ZIP-317 rate", async () => {
    estimateAccountMaxSpendable.mockResolvedValue(new BigNumber(123_000));

    const max = await estimate({ account, transaction: tx({}) });

    expect(max.toNumber()).toBe(123_000);
    expect(estimateAccountMaxSpendable).toHaveBeenCalledWith(
      expect.anything(),
      expect.anything(),
      40,
      [],
      [T1],
    );
  });

  it("never reports a negative max", async () => {
    estimateAccountMaxSpendable.mockResolvedValue(new BigNumber(-5));

    expect((await estimate({ account })).toNumber()).toBe(0);
  });
});

describe("buildLegacyBroadcast", () => {
  const broadcast = buildLegacyBroadcast(testContext);
  const HASH = "ab".repeat(32);
  const submit = () =>
    broadcast({
      account,
      signedOperation: {
        signature: "signed-hex",
        operation: {
          id: "op",
          hash: "",
          extra: { inputRefs: [{ hash: HASH, outputIndex: 0, address: T1 }] },
        } as unknown as Operation,
      } as SignedOperation,
    });

  it("broadcasts through the explorer and stamps the hash", async () => {
    fetchUtxoTx.mockResolvedValue({ outputs: [{ output_index: 0, spent_at_height: null }] });
    broadcastTx.mockResolvedValue("cc".repeat(32));

    const operation = await submit();

    expect(fetchUtxoTx).toHaveBeenCalledWith(HASH);
    expect(operation.hash).toBe("cc".repeat(32));
  });

  it("refuses to broadcast a UTXO already spent on chain", async () => {
    fetchUtxoTx.mockResolvedValue({ outputs: [{ output_index: 0, spent_at_height: 3_400_000 }] });

    await expect(submit()).rejects.toThrow("utxos already spent");
    expect(broadcastTx).not.toHaveBeenCalled();
  });
});
