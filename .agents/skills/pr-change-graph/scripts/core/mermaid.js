import { TEST_FILE } from "./graph.js";
import { compare, labelInPackage } from "./text.js";

/** @import { Commits, ExternalNode, GraphNode, LaidOutGraph, PackageNode } from "./types.js" */

/**
 * The commits the diagram is drawn for, and the URL each changed file's label links to, if any.
 * @typedef {Commits & { link?: (rel: string) => string }} Context
 */

const STYLES = {
  added: "fill:#dafbe1,stroke:#1a7f37,color:#1f2328",
  modified: "fill:#fff8c5,stroke:#9a6700,color:#1f2328",
  deleted: "fill:#ffebe9,stroke:#cf222e,color:#1f2328,stroke-dasharray:4 3",
  unchanged: "fill:#f6f8fa,stroke:#8c959f,color:#57606a",
  external: "fill:#ffffff,stroke:#8c959f,color:#57606a,stroke-dasharray:2 2",
};

// Removed edges stay solid, told apart by color only: GitHub drops dotted or dashed patterns from
// edges it redraws with line jumps.
const ARROWS = { added: "==>", removed: "-->", kept: "-->" };

// The legend's items, left to right, each labelled with its class.
const LEGEND = ["added", "modified", "deleted", "unchanged"];

/** Most characters in a diagram that GitHub renders: Mermaid's default `maxTextSize`. */
export const MAX_TEXT_SIZE = 50_000;

/**
 * The graph as a Mermaid flowchart: each package box with its files, the other packages and the external
 * packages, and the imports and dependencies between them, in an unlabelled box above a legend of the colors.
 * @param {LaidOutGraph} graph
 * @param {Context} context
 */
export function renderMermaid(graph, { base, head, baseBranch, link }) {
  const { nodes, edges, boxes } = graph;
  // A package with a box is drawn as that box, which takes the package's key: edges to it go to the box.
  const ids = assignIds(nodes.map(node => node.key));
  /** @param {GraphNode} node */
  const id = node => /** @type {string} */ (ids.get(node.key));
  const loose = nodes.filter(
    /** @returns {node is PackageNode | ExternalNode} */
    node => node.kind === "external" || (node.kind === "package" && !boxes.has(node)),
  );

  const lines = [
    // White package boxes, so they do not read as the yellow of modified files. Gray arrows from the
    // theme, as `linkStyle default` would also draw the legend's invisible links.
    '%%{init: {"themeVariables": {"clusterBkg": "#ffffff", "lineColor": "#8c959f"}}}%%',
    "%% Change graph generated by branch-graph",
    `%% base ${base}${baseBranch ? ` (merge base with ${baseBranch})` : ""}`,
    `%% head ${head}`,
    // The graph in an unlabelled box going its own way, then the legend under it.
    "flowchart TB",
    '  subgraph changes [" "]',
    `    direction ${graph.direction}`,
  ];
  const sortedBoxes = [...boxes].sort(
    ([a], [b]) => compare(a.label, b.label) || compare(a.dir, b.dir),
  );
  for (const [pkg, { direction, files }] of sortedBoxes) {
    const box = id(pkg);
    lines.push(`    subgraph ${box} ["${escapeLabel(pkg.label)}"]`, `      direction ${direction}`);
    // Mermaid drops the direction of a box that another box points at, so a direction other than the
    // graph's goes on an unlabelled box around the files, which no edge points at.
    const inner = direction === graph.direction ? null : `${box}_files`;
    if (inner) lines.push(`      subgraph ${inner} [" "]`, `        direction ${direction}`);
    const indent = inner ? "        " : "      ";
    for (const node of files) {
      const text = escapeLabel(labelInPackage(node.rel, pkg.dir));
      // A link in the label, not a `click` line: Mermaid strips the target of `click` links, which
      // then open inside GitHub's diagram iframe, where github.com refuses to load.
      const linked = link && node.status !== "unchanged";
      const label = linked ? `<a href='${link(node.rel)}' target='_blank'>${text}</a>` : text;
      const shape = TEST_FILE.test(node.rel) ? `(["${label}"])` : `["${label}"]`;
      lines.push(`${indent}${id(node)}${shape}:::${node.status}`);
    }
    if (inner) lines.push("      end", `      style ${inner} fill:none,stroke:none`);
    // Outlined like a file of the package's status.
    const outline = STYLES[pkg.status].split(",").filter(part => part.startsWith("stroke"));
    lines.push("    end", `    style ${box} ${outline.join(",")}`);
  }
  for (const node of loose.sort(byKey)) {
    const label = escapeLabel(node.kind === "external" ? node.name : node.label);
    lines.push(
      `    ${id(node)}["${label}"]:::${node.kind === "external" ? "external" : node.status}`,
    );
  }
  lines.push(
    "  end",
    "  style changes fill:none,stroke:none",
    '  subgraph legend [" "]',
    "    direction LR",
  );
  for (const status of LEGEND) lines.push(`    legend_${status}["${status}"]:::${status}`);
  lines.push("  end", "  style legend fill:none,stroke:none");

  /** @type {{ added: number[], removed: number[], kept?: number[] }} */
  const styled = { added: [], removed: [] };
  const ordered = edges.toSorted((a, b) => byKey(a.from, b.from) || byKey(a.to, b.to));
  ordered.forEach((edge, index) => {
    const text = edge.dev ? "|devDependency|" : "";
    lines.push(`  ${id(edge.from)} ${ARROWS[edge.status]}${text} ${id(edge.to)}`);
    styled[edge.status]?.push(index);
  });
  // Invisible links, after the drawn ones so as not to shift their indices: the legend under the graph,
  // and its items chained in a row.
  const legend = LEGEND.map(status => `legend_${status}`);
  lines.push("  changes ~~~ legend", `  ${legend.join(" ~~~ ")}`);
  if (styled.added.length)
    lines.push(`  linkStyle ${styled.added.join(",")} stroke:#1a7f37,stroke-width:2px`);
  if (styled.removed.length)
    lines.push(`  linkStyle ${styled.removed.join(",")} stroke:#cf222e,stroke-width:1.5px`);

  lines.push(...Object.entries(STYLES).map(([name, style]) => `  classDef ${name} ${style}`));
  return `${lines.join("\n")}\n`;
}

/**
 * Text for a double-quoted Mermaid label.
 * @param {string} text
 */
export function escapeLabel(text) {
  return text.replace(/"/g, "#quot;");
}

/**
 * Mermaid ids from node keys, numbered in sorted key order. Short, so that big diagrams stay under
 * the 50,000 characters GitHub renders; ids from the paths took most of that.
 * @param {string[]} keys
 */
function assignIds(keys) {
  return new Map(keys.toSorted().map((key, i) => [key, `n${i}`]));
}

/**
 * @param {GraphNode} a
 * @param {GraphNode} b
 */
function byKey(a, b) {
  return compare(a.key, b.key);
}
